import test from "node:test";
import assert from "node:assert/strict";
import {MiB,PLANS,evaluatePlan,canStartLive,canReserveUpload,STREAM_DEFAULTS} from "../social/live-media-entitlements.mjs";
const zero={planId:"free",usedLiveMinutes:0,usedViewerMinutes:0,activeStreams:0};
const upload={planId:"free",usedStorageBytes:0,usedMonthlyUploadBytes:0,incomingBytes:MiB};
test("no platform recording by default",()=>assert.equal(STREAM_DEFAULTS.platformRecording,false));
test("no replay by default",()=>assert.equal(STREAM_DEFAULTS.platformReplay,false));
test("cannot prevent viewer capture",()=>assert.equal(STREAM_DEFAULTS.canBlockThirdPartyCapture,false));
test("free tier available",()=>assert.equal(evaluatePlan("free").liveMinutes,60));
test("unknown tier denied",()=>assert.throws(()=>evaluatePlan("admin")));
test("live within cap",()=>assert.equal(canStartLive(zero).allowed,true));
test("concurrent stream denied",()=>assert.equal(canStartLive({...zero,activeStreams:1}).allowed,false));
test("minutes quota denied",()=>assert.equal(canStartLive({...zero,usedLiveMinutes:60}).reason,"broadcast-time"));
test("viewer delivery quota denied",()=>assert.equal(canStartLive({...zero,usedViewerMinutes:500}).reason,"audience-delivery"));
test("negative usage fails",()=>assert.throws(()=>canStartLive({...zero,usedViewerMinutes:-1})));
test("upload within cap",()=>assert.equal(canReserveUpload(upload).allowed,true));
test("exhausted storage quota",()=>assert.equal(canReserveUpload({...upload,usedStorageBytes:500*MiB}).reason,"storage"));
test("exhausted monthly upload quota",()=>assert.equal(canReserveUpload({...upload,usedMonthlyUploadBytes:750*MiB}).reason,"upload-limit"));
test("oversized single file",()=>assert.equal(canReserveUpload({...upload,incomingBytes:46*MiB}).reason,"single-file"));
test("empty file denied",()=>assert.equal(canReserveUpload({...upload,incomingBytes:0}).reason,"empty"));
test("negative upload usage denied",()=>assert.throws(()=>canReserveUpload({...upload,usedStorageBytes:-1})));
test("paid tiers have larger storage",()=>assert.ok(PLANS.creator.storedMiB>PLANS.supporter.storedMiB));
